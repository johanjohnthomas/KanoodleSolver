import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { Vector3 } from 'three';
import { sceneCamera } from './scene-camera.mjs';

const baseURL = process.env.PLAYWRIGHT_BASE_URL ?? 'http://127.0.0.1:4173/';
const dir = process.env.QA_EVIDENCE_DIR ?? '.omo/evidence/start-game';
await mkdir(dir, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader'] });
const errors = []; const results = [];
try {
  for (const [width, height, reducedMotion] of [[1280, 900, 'no-preference'], [768, 1024, 'no-preference'], [375, 900, 'no-preference'], [320, 740, 'no-preference'], [844, 390, 'no-preference'], [1280, 900, 'reduce']]) {
    const page = await browser.newPage({ viewport: { width, height }, hasTouch: true, reducedMotion });
    page.on('pageerror', error => errors.push(`${width}/${reducedMotion}: ${error.message}`));
    await page.goto(baseURL, { waitUntil: 'networkidle' });
    await page.getByLabel('Room settings', { exact: true }).click();
    const activity = page.getByLabel('Outdoor activity', { exact: true });
    if (await activity.isEnabled()) await activity.uncheck();
    if (width === 375) await page.getByLabel('Time of day', { exact: true }).selectOption('night');
    await page.getByLabel('Room settings', { exact: true }).click();
    await page.locator('.tabletop-canvas canvas').waitFor(); await page.waitForTimeout(1800);
    const prefix = `${width}-${reducedMotion}`;
    const capture = async name => { await page.waitForTimeout(350); await page.screenshot({ path: `${dir}/${prefix}-${name}.png` }); };
    assert.equal(await page.getByRole('button', { name: 'Piece A', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Solve board', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Play', exact: true }).scrollIntoViewIfNeeded();
    const project = async (point, overhead = false) => {
      const bounds = await page.locator('.tabletop-canvas').boundingBox(); assert(bounds);
      const p = new Vector3(...point).project(sceneCamera(bounds, overhead));
      return { x: bounds.x + (p.x + 1) * bounds.width / 2, y: bounds.y + (1 - p.y) * bounds.height / 2 };
    };
    const source = await project([-8.161, .46, -3.873]);
    const target = await project([-4.5, .65, -2]);
    await page.mouse.move(source.x, source.y); await page.mouse.down();
    await page.mouse.move(target.x, target.y, { steps: 12 }); await page.mouse.up();
    await page.keyboard.press('r'); await page.keyboard.press('f');
    await capture('start');
    const handle = await project([0, -1.15, 8.93]);
    await page.touchscreen.tap(handle.x, handle.y);
    await page.getByRole('img', { name: /Made for Rach with love <3/ }).waitFor();
    await page.waitForTimeout(1600); await capture('drawer');
    await page.getByRole('button', { name: 'Play', exact: true }).focus(); await page.keyboard.press('Enter');
    await page.waitForTimeout(100); await page.screenshot({ path: `${dir}/${prefix}-transition.png` });
    await page.getByLabel('0 of 12 pieces placed').waitFor();
    await page.waitForTimeout(1800); await capture('playing');
    assert.equal(await page.getByRole('img', { name: /Made for Rach with love <3/ }).count(), 0);
    const activePiece = await project([-8.161, .46, -3.873], true);
    await page.touchscreen.tap(activePiece.x, activePiece.y);
    assert.match(await page.locator('.hand-status').innerText(), /Piece A/);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Check solvability', exact: true }).click();
    await page.getByText('This layout is solvable. No pieces changed.', { exact: true }).waitFor();
    await page.getByLabel('0 of 12 pieces placed').waitFor();
    assert.equal(await page.getByRole('button', { name: 'Undo', exact: true }).isDisabled(), true);
    await capture('solvable');
    await page.getByRole('button', { name: '2D board', exact: true }).click();
    await page.getByRole('button', { name: 'Select piece A', exact: true }).click();
    await page.getByRole('gridcell', { name: 'Row 1, column 10, empty', exact: true }).click();
    const before = await page.locator('[role="gridcell"][data-piece]').evaluateAll(nodes => nodes.map(n => n.getAttribute('aria-label')));
    await page.getByRole('button', { name: 'Check solvability', exact: true }).click();
    await page.getByText('This layout cannot be completed as it is. No pieces changed.', { exact: true }).waitFor();
    assert.deepEqual(await page.locator('[role="gridcell"][data-piece]').evaluateAll(nodes => nodes.map(n => n.getAttribute('aria-label'))), before);
    assert.equal(await page.locator('[data-recovery]').count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Lift highlighted pieces', exact: true }).count(), 0);
    await capture('blocked');
    await page.getByRole('button', { name: 'Hint', exact: true }).click();
    await page.getByRole('button', { name: 'Lift highlighted pieces', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Check solvability', exact: true }).click();
    await page.getByText('This layout cannot be completed as it is. No pieces changed.', { exact: true }).waitFor();
    assert.equal(await page.locator('[data-recovery]').count(), 0);
    await page.getByRole('button', { name: '3D desk', exact: true }).click();
    await page.getByRole('button', { name: 'Desk view', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Piece A', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Play', exact: true }).click();
    await page.getByLabel('1 of 12 pieces placed').waitFor();
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    await page.getByLabel('0 of 12 pieces placed').waitFor();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth); assert.equal(overflow, 0);
    results.push({ width, height, reducedMotion, lockedStart: true, drawer: true, play: 'overhead', resumed: true, spoilerFreeCheck: true, unchangedHistory: true, overflow });
    await page.close();
  }
  assert.deepEqual(errors, []);
  await writeFile(`${dir}/qa.json`, JSON.stringify({ baseURL, results, errors }, null, 2)); console.log(JSON.stringify({ results, errors }, null, 2));
} finally { await browser.close(); }
